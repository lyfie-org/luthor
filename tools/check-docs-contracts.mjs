/**
 * Keeps the documentation honest against the code it describes.
 *
 * Docs pages carry frontmatter naming the exports and props they cover
 * and the source files they were last verified from. Nothing enforced
 * any of it, so a renamed export or a deleted prop left the page quietly
 * wrong — worse than no page, because readers trust it.
 *
 * Three checks, all cheap enough to run on every push:
 *
 *  1. every `exports:` entry exists in the package's generated API
 *     inventory,
 *  2. every `props:` entry appears in that package's built type surface,
 *  3. every `lastVerifiedFrom:` path still exists on disk.
 *
 * Run after `pnpm build` and `apps/web`'s `sync:docs`, since it reads
 * both the built `.d.ts` and the generated inventory.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOCS_DIR = path.join(ROOT, "apps/web/src/content/docs");
const INVENTORY_PATH = path.join(
  DOCS_DIR,
  "reference/api-inventory.generated.json",
);

const PACKAGE_DIRS = {
  luthor: "packages/luthor",
  headless: "packages/headless",
};

const violations = [];
const staleInventoryEntries = new Set();

/** Minimal frontmatter reader: string scalars and `- item` lists only. */
function parseFrontmatter(source) {
  if (!source.startsWith("---")) {
    return null;
  }
  const end = source.indexOf("\n---", 3);
  if (end === -1) {
    return null;
  }

  const block = source.slice(3, end);
  const result = {};
  let currentKey = null;

  for (const rawLine of block.split("\n")) {
    const line = rawLine.replace(/\s+$/, "");
    if (!line.trim()) {
      continue;
    }

    const listItem = line.match(/^\s+-\s+(.*)$/);
    if (listItem && currentKey) {
      const value = listItem[1].trim().replace(/^["']|["']$/g, "");
      if (value) {
        result[currentKey].push(value);
      }
      continue;
    }

    const keyed = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!keyed) {
      continue;
    }

    const [, key, rest] = keyed;
    currentKey = key;
    const trimmed = rest.trim();
    if (trimmed === "" || trimmed === "[]") {
      result[key] = [];
    } else {
      result[key] = trimmed.replace(/^["']|["']$/g, "");
      currentKey = null;
    }
  }

  return result;
}

async function listMarkdownFiles(dirPath) {
  const entries = await fs.readdir(dirPath, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const entryPath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listMarkdownFiles(entryPath)));
    } else if (entry.name.endsWith(".md")) {
      files.push(entryPath);
    }
  }
  return files;
}

async function readTypeSurface(packageKey) {
  const packageDir = PACKAGE_DIRS[packageKey];
  if (!packageDir) {
    return null;
  }

  const distDir = path.join(ROOT, packageDir, "dist");
  let entries;
  try {
    entries = await fs.readdir(distDir);
  } catch {
    return null;
  }

  const declarations = entries.filter((name) => name.endsWith(".d.ts"));
  if (declarations.length === 0) {
    return null;
  }

  const contents = await Promise.all(
    declarations.map((name) => fs.readFile(path.join(distDir, name), "utf8")),
  );
  return contents.join("\n");
}

function relative(filePath) {
  return path.relative(ROOT, filePath).split(path.sep).join("/");
}

async function main() {
  let inventory;
  try {
    inventory = JSON.parse(await fs.readFile(INVENTORY_PATH, "utf8"));
  } catch {
    console.error(
      `Missing API inventory at ${relative(INVENTORY_PATH)}. Run "pnpm --dir apps/web run sync:docs" first.`,
    );
    process.exit(2);
  }

  const inventorySets = Object.fromEntries(
    Object.entries(inventory).map(([key, names]) => [key, new Set(names)]),
  );

  const typeSurfaces = {};
  for (const key of Object.keys(PACKAGE_DIRS)) {
    typeSurfaces[key] = await readTypeSurface(key);
  }

  const files = await listMarkdownFiles(DOCS_DIR);

  for (const file of files) {
    const source = await fs.readFile(file, "utf8");
    const frontmatter = parseFrontmatter(source);
    if (!frontmatter) {
      continue;
    }

    const docPath = relative(file);
    const packageKey = frontmatter.package;

    // 1. Documented exports must exist in the built type surface. The
    //    committed inventory is checked separately below: it is not
    //    regenerated by sync:docs, so it drifts and cannot be the source
    //    of truth here.
    const documentedExports = Array.isArray(frontmatter.exports)
      ? frontmatter.exports
      : [];
    const surfaceForExports = typeSurfaces[packageKey];
    if (surfaceForExports) {
      for (const exportName of documentedExports) {
        const exported = new RegExp(
          `\\b(?:declare\\s+)?(?:const|function|class|type|interface|enum)\\s+${exportName}\\b|\\b${exportName}\\s+as\\b|\\bas\\s+${exportName}\\b|[{,]\\s*${exportName}\\s*[,}]`,
        ).test(surfaceForExports);
        if (!exported) {
          violations.push(
            `${docPath}: documents export "${exportName}", which is not in the built ${packageKey} type surface.`,
          );
        }
      }

      // Advisory: keep the committed inventory from silently rotting.
      const inventorySet = inventorySets[packageKey];
      if (inventorySet) {
        for (const exportName of documentedExports) {
          if (!inventorySet.has(exportName)) {
            staleInventoryEntries.add(`${packageKey}: ${exportName}`);
          }
        }
      }
    }

    // 2. Documented props must appear in the built type surface.
    const documentedProps = Array.isArray(frontmatter.props)
      ? frontmatter.props
      : [];
    const typeSurface = typeSurfaces[packageKey];
    if (typeSurface) {
      for (const propName of documentedProps) {
        const declared = new RegExp(`\\b${propName}\\??\\s*:`).test(typeSurface);
        if (!declared) {
          violations.push(
            `${docPath}: documents prop "${propName}", which is not declared in the ${packageKey} type surface.`,
          );
        }
      }
    }

    // 3. lastVerifiedFrom must point at files that still exist.
    const verifiedFrom = Array.isArray(frontmatter.lastVerifiedFrom)
      ? frontmatter.lastVerifiedFrom
      : [];
    for (const sourcePath of verifiedFrom) {
      try {
        await fs.stat(path.join(ROOT, sourcePath));
      } catch {
        violations.push(
          `${docPath}: lastVerifiedFrom points at "${sourcePath}", which no longer exists.`,
        );
      }
    }
  }

  if (staleInventoryEntries.size > 0) {
    console.warn(
      `Note: api-inventory.generated.json is missing ${staleInventoryEntries.size} documented export(s):`,
    );
    for (const entry of staleInventoryEntries) {
      console.warn(`  - ${entry}`);
    }
    console.warn(
      "That file is not regenerated by sync:docs, so it drifts. Advisory only, not a failure.\n",
    );
  }

  if (violations.length > 0) {
    console.error("Documentation contract checks failed:\n");
    for (const violation of violations) {
      console.error(`  - ${violation}`);
    }
    console.error(
      `\n${violations.length} problem(s). Update the docs or the frontmatter that describes them.`,
    );
    process.exit(1);
  }

  console.log(`Documentation contract checks passed (${files.length} pages).`);
}

main().catch((error) => {
  console.error("check-docs-contracts failed to run:", error);
  process.exit(2);
});
